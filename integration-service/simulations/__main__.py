"""``python -m simulations [name ...] [--output FILE]``: runs the simulations and prints their evidence.

Needs the running stack (``docker compose up``). Exits non-zero if any simulation fails its checks.
"""

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path

from simulations.harness import Stack
from simulations.scenarios import SCENARIOS

HEADER = """# Simulations

Generated by `make simulate` against the running stack on {timestamp}. Every value below was read from the system
it describes: Fineract through its own API, the ERP through its own API, the integration service from its database.
Fineract and ERP values are shown exactly as those systems return them (for example `4125599.0` from Fineract).
Each simulation is also an automated test (`make test-stack`).

| Simulation | Result |
| --- | --- |
{summary}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("names", nargs="*", help=f"simulations to run (default: all): {', '.join(SCENARIOS)}")
    parser.add_argument("--output", type=Path, help="also write the evidence to this Markdown file")
    arguments = parser.parse_args()
    unknown = sorted(set(arguments.names) - SCENARIOS.keys())
    if unknown:
        parser.error(f"unknown simulations: {', '.join(unknown)}")

    stack = Stack()
    results = []
    for name in arguments.names or list(SCENARIOS):
        try:
            evidence = SCENARIOS[name](stack)
        finally:
            stack.clear_faults()
        print(evidence.to_markdown(), flush=True)
        results.append(evidence)

    if arguments.output:
        summary = "\n".join(f"| {e.title} | {'PASS' if e.passed else 'FAIL'} |" for e in results)
        header = HEADER.format(timestamp=datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC"), summary=summary)
        arguments.output.write_text(header + "\n" + "\n".join(e.to_markdown() for e in results))
    return 0 if all(evidence.passed for evidence in results) else 1


if __name__ == "__main__":
    sys.exit(main())
